  it('session/agents-type-from-meta', () => {
    const main = transcript();
    const toolUseId = main.agent({ agentId: 'b1', type: 'general-purpose', description: 'Review the cart' });
    const meta = agentMeta({ agentType: 'reviewer', description: 'Review the cart', spawnDepth: 1, toolUseId });
    // The meta file's type wins over the call's subagent_type.
    const digest = digestOf({ main, metas: { b1: meta } });
    expect(digest.runs).toHaveLength(1);
    expect(digest.runs[0]).toMatchObject({ agentId: 'b1', toolUseId, type: 'reviewer', spawnDepth: 1, description: 'Review the cart' });

    // Read before the transcript, the meta file's run is folded into the call's run on agentId.
    const early = emptyDigest();
    applyAgentMeta(early, 'b1', { ...meta, toolUseId: undefined }, CONTEXT);
    applyMainChunk(early, chunkOf(main.jsonl()), CONTEXT);
    finalizeDigest(early, { active: false });
    expect(early.runs).toHaveLength(1);
    expect(early.runs[0]).toMatchObject({ agentId: 'b1', toolUseId, type: 'reviewer', spawnDepth: 1 });
  });

