  it('session/resume-from-offset-partial-line', () => {
    const main = transcript().prompt('One');
    main.agent({ agentId: 'r1' });
    main.prompt('Two').handback('r1', 'Report of r1').prompt('Three');
    const full = Buffer.from(main.jsonl(), 'utf8');
    // Cut inside the line of prompt `Two`: the Agent call is in, its handback is not.
    const cut = full.indexOf(Buffer.from('"Two"')) + 2;

    const first = emptyDigest();
    applyMainChunk(first, { bytes: full.subarray(0, cut), offset: 0, fileSize: cut }, CONTEXT);
    finalizeDigest(first, { active: true });
    expect(promptTexts(first)).toEqual(['One']);
    expect(first.state.main.parsedBytes).toBe(full.lastIndexOf(0x0a, cut) + 1);
    expect(first.runs[0]).toMatchObject({ agentId: 'r1', status: 'running', report: null });

    // The stored digest is JSON; the next read starts at parsedBytes.
    const stored = JSON.parse(JSON.stringify(first)) as SessionDigest;
    const offset = stored.state.main.parsedBytes;
    applyMainChunk(stored, { bytes: full.subarray(offset), offset, fileSize: full.length }, CONTEXT);
    finalizeDigest(stored, { active: false });
    expect(promptTexts(stored)).toEqual(['One', 'Two', 'Three']);
    expect(stored.state.main.parsedBytes).toBe(full.length);
    expect(stored.runs).toHaveLength(1);
    expect(stored.runs[0]).toMatchObject({ report: 'Report of r1', status: 'completed', statusSource: 'handback' });

    // A chunk that does not start at the cursor is refused.
    expect(() => applyMainChunk(stored, chunkOf(main.jsonl()), CONTEXT)).toThrow(/cursor/);
  });

